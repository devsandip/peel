// Builds index.html and the png/ exports for each logo direction from the SVG sources.
// Run from the repository root: node ux/logos/directions/build.mjs
// Needs the workspace's Playwright Chromium, and network access for the Google Fonts wordmarks.
import { chromium } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const INK = '#292C28';
const DARK_TEXT = '#EFEEE4';

const directions = [
  {
    dir: '01-corner-lift',
    name: 'Corner lift',
    blurb: 'An amber note whose bottom-right corner curls up. A polished version of the folded-corner placeholder in the mockups.',
    font: { family: 'Geist', css: 'Geist:wght@600', weight: 600, tracking: '-0.045em' },
  },
  {
    dir: '02-note-window',
    name: 'Note window',
    blurb: 'A note with an amber title bar, one close dot and a folded corner, like the floating note that has only a Close button.',
    font: { family: 'Instrument Sans', css: 'Instrument+Sans:wght@600', weight: 600, tracking: '-0.03em' },
  },
  {
    dir: '03-p-monogram',
    name: 'P monogram',
    blurb: 'A bold P whose bowl carries a folded amber corner. The clearest of the five at 16 px.',
    font: { family: 'Bricolage Grotesque', css: 'Bricolage+Grotesque:opsz,wght@12..96,700', weight: 700, tracking: '-0.035em' },
  },
  {
    dir: '04-two-notes',
    name: 'Two notes',
    blurb: 'An amber note over a tilted ochre one: the library plus floating notes, or two synced devices.',
    font: { family: 'Figtree', css: 'Figtree:wght@700', weight: 700, tracking: '-0.03em' },
  },
  {
    dir: '05-peel-sticker',
    name: 'Peel sticker',
    blurb: 'A round amber sticker with its edge peeling back. The most distinctive shape, and the furthest from notes.',
    font: { family: 'Fraunces', css: 'Fraunces:opsz,wght,SOFT@9..144,600,100', weight: 600, tracking: '-0.02em', variation: "'SOFT' 100", fallback: 'serif' },
  },
];

const fontsHref = (list) =>
  `https://fonts.googleapis.com/css2?${list.map((d) => `family=${d.font.css}`).join('&')}&display=swap`;

const fontStyle = ({ font }) =>
  `font-family:'${font.family}',${font.fallback ?? 'sans-serif'};font-weight:${font.weight};letter-spacing:${font.tracking}` +
  (font.variation ? `;font-variation-settings:${font.variation}` : '');

const img = (d, file, size, alt = '') =>
  `<img src="${d.dir}/${file}" width="${size}" height="${size}" alt="${alt}">`;

const tile = (kind, label, inner) =>
  `<div class="tile ${kind}"><span class="label">${label}</span>${inner}</div>`;

const lockup = (d, theme) =>
  `<div class="lockup">${img(d, `mark-${theme}.svg`, 56)}<span style="${fontStyle(d)}">peel</span></div>`;

const sizes = (d, theme) =>
  `<div class="sizes">${img(d, `mark-${theme}.svg`, 64)}${img(d, `mark-${theme}.svg`, 32)}${img(d, `mark-small-${theme}.svg`, 16)}</div>`;

const section = (d, i) => `
<section id="${d.dir}">
  <h2>${i + 1}. ${d.name}</h2>
  <p>${d.blurb} Wordmark: ${d.font.family}.</p>
  <div class="board">
    ${tile('hero canvas', 'Mark', img(d, 'mark-light.svg', 220, `${d.name} mark`))}
    ${tile('canvas', 'App icon, light', img(d, 'app-icon-light.svg', 160))}
    ${tile('dark', 'App icon, dark', img(d, 'app-icon-dark.svg', 160))}
    ${tile('outline', 'Lockup, light', lockup(d, 'light'))}
    ${tile('dark', 'Lockup, dark', lockup(d, 'dark'))}
    ${tile('outline', '64, 32 and 16 px', sizes(d, 'light'))}
    ${tile('dark', '64, 32 and 16 px', sizes(d, 'dark'))}
  </div>
</section>`;

